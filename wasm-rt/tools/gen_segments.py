#!/usr/bin/env python3
from __future__ import annotations

import argparse
import os
import struct

__author__ = "carunodev @stfu"

SEG_COUNT = 4_077
LEN_CYCLE = (32, 0, 1, 64, 256, 17)

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
SRC = os.path.join(CRATE, "src")


def segment(i: int) -> bytes:
    n = LEN_CYCLE[i % len(LEN_CYCLE)]
    return bytes(((i * 31 + j * 17) & 0xFF) for j in range(n))


def main() -> int:
    global SRC
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture-output", required=True)
    args = parser.parse_args()
    destination = os.path.normcase(os.path.realpath(args.fixture_output))
    if destination == os.path.normcase(os.path.realpath(SRC)):
        parser.error("synthetic fixtures cannot replace engine segments")
    SRC = destination
    os.makedirs(SRC, exist_ok=True)
    blob = bytearray()
    lens = []
    for i in range(SEG_COUNT):
        seg = segment(i)
        lens.append(len(seg))
        blob += seg
    assert len(blob) <= 0x4000_0000, "blob must fit a wasm32 data offset"

    with open(os.path.join(SRC, "seg_blob.bin"), "wb") as fh:
        fh.write(blob)

    lines = []
    lines.append("//! Passive data segments of the recovered module.")
    lines.append("//!")
    lines.append("//! GENERATED by `tools/gen_segments.py` — do not edit by hand.")
    lines.append("//!")
    lines.append("//! The module declares `%d` passive segments (data section flags `0x04`," % SEG_COUNT)
    lines.append("//! no memory index). Their bytes live in `seg_blob.bin`; `SEG_OFFSETS` is the")
    lines.append("//! prefix sum of `SEG_LENS`, so `segment(i)` is a sub-slice of `SEG_BLOB` and")
    lines.append("//! `memory.init` copies out of it without any per-segment allocation.")
    lines.append("")
    lines.append("/// Number of passive segments in the module.")
    lines.append("pub const SEG_COUNT: usize = %d;" % SEG_COUNT)
    lines.append("")
    lines.append("/// Concatenated segment bytes (length `SEG_BLOB.len()`).")
    lines.append('pub static SEG_BLOB: &[u8] = include_bytes!("seg_blob.bin");')
    lines.append("")
    lines.append("/// Declared length of each segment, in index order.")
    lines.append("pub static SEG_LENS: [u32; SEG_COUNT] = [")
    for start in range(0, SEG_COUNT, 16):
        chunk = lens[start:start + 16]
        lines.append("    " + " ".join("%d," % n for n in chunk))
    lines.append("];")
    lines.append("")
    lines.append("/// Byte offset of each segment inside [`SEG_BLOB`], in index order.")
    lines.append("pub static SEG_OFFSETS: [u32; SEG_COUNT] = build_offsets();")
    lines.append("")
    lines.append("/// `SEG_OFFSETS` as a const-evaluated prefix sum of [`SEG_LENS`].")
    lines.append("const fn build_offsets() -> [u32; SEG_COUNT] {")
    lines.append("    let mut out = [0u32; SEG_COUNT];")
    lines.append("    let mut at = 0u32;")
    lines.append("    let mut i = 0usize;")
    lines.append("    while i < SEG_COUNT {")
    lines.append("        out[i] = at;")
    lines.append("        at += SEG_LENS[i];")
    lines.append("        i += 1;")
    lines.append("    }")
    lines.append("    out")
    lines.append("}")
    lines.append("")
    lines.append("/// Bytes of segment `i`, or `None` when the index is out of range.")
    lines.append("#[inline]")
    lines.append("pub fn segment(i: u32) -> Option<&'static [u8]> {")
    lines.append("    let i = usize::try_from(i).ok()?;")
    lines.append("    if i >= SEG_COUNT {")
    lines.append("        return None;")
    lines.append("    }")
    lines.append("    let off = SEG_OFFSETS[i] as usize;")
    lines.append("    let end = off + SEG_LENS[i] as usize;")
    lines.append("    SEG_BLOB.get(off..end)")
    lines.append("}")
    lines.append("")
    with open(os.path.join(SRC, "segments.rs"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

    # Summary for the caller.
    print("segments: %d, blob: %d bytes, empty: %d, max len: %d"
          % (SEG_COUNT, len(blob), lens.count(0), max(lens)))
    print("wrote src/seg_blob.bin, src/segments.rs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
