#!/usr/bin/env python3
"""Emit data segments of game.wasm as a flat blob + a (offset,len) table for wasm-rt.

All 4,077 segments in this module are *passive* (flags=1): they have no initializer
offset, memory is filled later by __wasm_init_memory (func 88) through memory.init.
The blob below is byte-identical to what that function copies.
"""
import json, os, sys

__author__ = "carunodev @stfu"

WASM = sys.argv[1]
OUTDIR = sys.argv[2]
os.makedirs(OUTDIR, exist_ok=True)
d = open(WASM, 'rb').read()


def leb(b, p):
    r = s = 0
    while True:
        x = b[p]; p += 1
        r |= (x & 0x7f) << s
        if not x & 0x80:
            return r, p
        s += 7


p = 8
secs = {}
while p < len(d):
    sid = d[p]; p += 1
    size, p = leb(d, p)
    secs.setdefault(sid, (p, size))
    p += size

off, size = secs[11]
p = off
cnt, p = leb(d, p)
table, blob = [], bytearray()
for i in range(cnt):
    flags, p = leb(d, p)
    if flags in (0, 2):                     # active segment: has a base expr
        if flags == 2:
            _m, p = leb(d, p)
        p += 1                              # opcode (i32/i64.const)
        _v, p = leb(d, p)
        assert d[p] == 0x0b, 'expected end'
        p += 1
    ln, p = leb(d, p)
    table.append((len(blob), ln))
    blob += d[p:p + ln]
    p += ln

with open(os.path.join(OUTDIR, 'segments.bin'), 'wb') as f:
    f.write(blob)

lines = ['// generated by tools/w2r/gen_segments.py — do not edit',
         'pub const SEG_COUNT: usize = %d;' % len(table),
         'pub static SEG_BLOB: &[u8] = include_bytes!("segments.bin");',
         'pub const SEG_TAB: [(u32, u32); %d] = [' % len(table)]
for o, l in table:
    lines.append('    (%d, %d),' % (o, l))
lines.append('];')
lines += [
    'pub static SEG_LENS: [u32; SEG_COUNT] = lengths();',
    'pub static SEG_OFFSETS: [u32; SEG_COUNT] = offsets();',
    'const fn lengths() -> [u32; SEG_COUNT] {',
    '    let mut out = [0; SEG_COUNT];',
    '    let mut i = 0;',
    '    while i < SEG_COUNT { out[i] = SEG_TAB[i].1; i += 1; }',
    '    out',
    '}',
    'const fn offsets() -> [u32; SEG_COUNT] {',
    '    let mut out = [0; SEG_COUNT];',
    '    let mut i = 0;',
    '    while i < SEG_COUNT { out[i] = SEG_TAB[i].0; i += 1; }',
    '    out',
    '}',
    'pub fn segment(i: u32) -> Option<&\'static [u8]> {',
    '    let &(start, len) = SEG_TAB.get(i as usize)?;',
    '    SEG_BLOB.get(start as usize..start as usize + len as usize)',
    '}',
]
open(os.path.join(OUTDIR, 'segments.rs'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')

json.dump({'segments': len(table), 'bytes': len(blob), 'wasm_size': len(d)},
          open(os.path.join(OUTDIR, 'segments.json'), 'w'), indent=1)
print(f'segments={len(table)} blob={len(blob)}')
print(f'first 3: {table[:3]}')
print(f'largest: {max(table, key=lambda t: t[1])}')
